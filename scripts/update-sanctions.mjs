// Downloads the OFAC SDN digital-currency address lists (extracted nightly by
// github.com/0xB10C/ofac-sanctioned-digital-currency-addresses) and writes the
// bundled snapshot used by the engine as a fallback when D1 has no fresher copy.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

export const SANCTION_ASSETS = ['ETH', 'XBT', 'TRX', 'USDT', 'USDC', 'BSC'];
const BASE =
  'https://raw.githubusercontent.com/0xB10C/ofac-sanctioned-digital-currency-addresses/lists';

const out = fileURLToPath(new URL('../packages/engine/src/sanctions/snapshot.ts', import.meta.url));

const lists = {};
for (const asset of SANCTION_ASSETS) {
  const res = await fetch(`${BASE}/sanctioned_addresses_${asset}.txt`);
  if (!res.ok) throw new Error(`${asset}: HTTP ${res.status}`);
  const text = await res.text();
  lists[asset] = [...new Set(text.split(/\r?\n/).map((l) => l.trim()).filter(Boolean))];
  console.log(`${asset}: ${lists[asset].length}`);
}

const body = `// AUTO-GENERATED by scripts/update-sanctions.mjs — do not edit by hand.
// Source: OFAC SDN list via github.com/0xB10C/ofac-sanctioned-digital-currency-addresses
export const SANCTIONS_SNAPSHOT_DATE = '${new Date().toISOString().slice(0, 10)}';

export const SANCTIONS_SNAPSHOT: Record<string, string[]> = ${JSON.stringify(lists, null, 1)};
`;
await writeFile(out, body);
console.log(`wrote ${out}`);
